const fs=require('node:fs');
const path=require('node:path');
const {execFileSync}=require('node:child_process');
const directory=path.join(__dirname,'workflow-cleanup'),root=path.resolve(__dirname,'../..');
const env={...process.env,GIT_TERMINAL_PROMPT:'0',GCM_INTERACTIVE:'Never'};
const git=(args)=>execFileSync('git',args,{cwd:directory,env,encoding:'utf8',timeout:60000}).trim();
const file='.github/workflows/cron_crawler.yml';
const expected='0f6a8301f146ab63536252973d307783f051c3d3';
if(git(['rev-parse',`HEAD:${file}`])!==expected)throw Error('원격 예약 파일이 변경되어 다시 확인해야 합니다.');
git(['read-tree','HEAD']);
const replacement=fs.readFileSync(path.join(root,file),'utf8').replace(/\r\n/g,'\n');
const original=git(['show',`HEAD:${file}`])+'\n';
if(replacement!==original.replace(/  schedule:\n    # 한국 시간 09:00·21:00\. GitHub 스케줄은 지연될 수 있다\.\n    - cron: '0 0,12 \* \* \*'\n/,'  # 정기 조사는 Cloudflare vdebut-discovery가 수행한다. 이 워크플로는 수동 보고만 유지한다.\n'))throw Error('예상한 예약 제거 외 변경이 있습니다.');
const blob=execFileSync('git',['hash-object','-w','--stdin'],{cwd:directory,env,input:replacement,encoding:'utf8'}).trim();
git(['update-index','--add','--cacheinfo',`100644,${blob},${file}`]);
const changed=git(['diff','--cached','--name-only']);if(changed!==file)throw Error('단일 예약 파일 변경이 아닙니다.');
console.log(git(['diff','--cached','--stat']));
const tree=git(['write-tree']),parent=git(['rev-parse','HEAD']);
const commit=git(['-c','user.name=Codex','-c','user.email=codex@openai.com','commit-tree',tree,'-p',parent,'-m','chore: move scheduled debut investigation to Cloudflare [skip ci]']);
fs.writeFileSync(path.join(__dirname,'workflow-cleanup-commit.json'),JSON.stringify({commit,parent,file,blob},null,2)+'\n');
if(process.argv[2]==='--push')console.log(git(['push','origin',`${commit}:refs/heads/main`]));
console.log(JSON.stringify({commit,parent,file,pushed:process.argv[2]==='--push'}));
